const ADVANCE = 6;

// How wide a line is in art pixels, `size` art pixels to each of the font's
export const textWidth = (text, size = 1) => String(text).length * ADVANCE * size;

// A line of words at (x, y), y its baseline, on whole art pixels: capitals only, and anything the font lacks as a
// question mark. Cut to `max` art pixels wide, it ends where it's cut.
export const pixelText = (ctx, text, x, y, { color, size = 1, align = 'left', max = Infinity }) => {
	const unit = size;
	const fits = Math.max(0, Math.floor(max / (ADVANCE * unit)));
	const line = String(text).toUpperCase().slice(0, fits);
	const width = textWidth(line, size);
	const start = { left: x, center: x - width / 2, right: x - width }[align];
	const left = Math.round(start);
	const top = Math.round(y) - 7 * unit;

	if (line) ctx.drawImage(lineImage(line, color), left, top, width, 7 * unit);
};

// Each line as drawn, a pixel to each of the font's, by its words and color; few enough are ever on screen at once
// that starting over past a few hundred keeps it bounded without missing much
const lines = new Map();
const lineImage = (line, color) => {
	const key = `${color}|${line}`;
	const held = lines.get(key);

	if (held) return held;
	if (lines.size > 400) lines.clear();

	const canvas = document.createElement('canvas');
	const ctx = canvas.getContext('2d');

	canvas.width = Math.max(1, textWidth(line));
	canvas.height = 7;
	ctx.fillStyle = color;
	[...line].forEach((character, index) => {
		const rows = GLYPHS[character] ?? GLYPHS['?'];

		rows.forEach((row, rowIndex) => {
			for (let column = 0; column < 5; column++)
				if (row[column] === '1') ctx.fillRect(index * ADVANCE + column, rowIndex, 1, 1);
		});
	});
	lines.set(key, canvas);

	return canvas;
};
